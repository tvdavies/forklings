// Writes src/shared/classic-looks.ts: the classics' worn looks, precomputed so the nightly
// generator doesn't draw them on every cold start. Run after changing a classic's art:
//   bun scripts/classic-looks.ts
// (test/unit/shop.test.ts fails until the file matches the art.)
import { writeFileSync } from 'node:fs';
import { ITEMS } from '../src/shared/compose';
import { encodeLook, lookOf } from '../src/shared/distinct';
import { CLASSICS } from '../src/shared/economy';

const lines = Object.keys(CLASSICS).map(
  (id) => `  ${/^[a-z]\w*$/.test(id) ? id : JSON.stringify(id)}: '${encodeLook(lookOf(ITEMS[id], id))}',`,
);
writeFileSync(
  new URL('../src/shared/classic-looks.ts', import.meta.url),
  `// Generated by scripts/classic-looks.ts: the classics' worn looks (encodeLook), for the shop's
// distinctness check. Don't edit by hand; regenerate after changing a classic's art.
import { decodeLook, type Look } from './distinct';

export const CLASSIC_LOOKS: Record<string, string> = {
${lines.join('\n')}
};

let decoded: Record<string, Look> | null = null;
export function classicLooks(): Record<string, Look> {
  decoded ??= Object.fromEntries(Object.entries(CLASSIC_LOOKS).map(([id, s]) => [id, decodeLook(s)]));
  return decoded;
}
`,
);
console.log(`wrote ${lines.length} classic looks`);
